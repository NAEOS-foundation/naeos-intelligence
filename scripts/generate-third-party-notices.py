#!/usr/bin/env python3
"""Generate a deterministic Go module inventory for THIRD-PARTY-NOTICES.md.

Requires Go modules to be downloaded first (go mod download). Module/license state
is derived from 'go list -m -json all' and license files in each module cache dir.
"""
import json
import subprocess
import sys
from pathlib import Path

OUTPUT = Path("THIRD-PARTY-NOTICES.md")
LICENSE_NAMES = ("LICENSE", "LICENSE.txt", "LICENSE.md", "COPYING", "NOTICE")

def stream_json(raw):
    decoder = json.JSONDecoder()
    index = 0
    while index < len(raw):
        while index < len(raw) and raw[index].isspace():
            index += 1
        if index == len(raw):
            break
        value, index = decoder.raw_decode(raw, index)
        yield value

def classify(text):
    head = text[:5000].lower()
    if "apache license" in head and "version 2.0" in head:
        return "Apache-2.0"
    if "mit license" in head or ("permission is hereby granted, free of charge" in head and "the software" in head):
        return "MIT"
    if "redistribution and use in source and binary forms" in head:
        if "neither the name" in head or "endorse or promote" in head:
            return "BSD-3-Clause"
        return "BSD-2-Clause"
    if "mozilla public license" in head:
        return "MPL-2.0"
    if "gnu lesser general public license" in head:
        return "LGPL (review required)"
    if "gnu general public license" in head:
        return "GPL (review required)"
    return "UNKNOWN (manual review required)"

def main():
    raw = subprocess.check_output(["go", "list", "-m", "-json", "all"], text=True)
    modules = list(stream_json(raw))
    rows = []
    for mod in sorted(modules, key=lambda item: item["Path"]):
        path, version = mod["Path"], mod.get("Version", "(main module)")
        directory = Path(mod.get("Dir", ""))
        candidates = [directory / name for name in LICENSE_NAMES]
        found = next((candidate for candidate in candidates if candidate.is_file()), None)
        license_id = classify(found.read_text(errors="replace")) if found else "UNKNOWN (license file not found)"
        if license_id.startswith("UNKNOWN") or "review required" in license_id:
            print(f"License review required: {path}@{version}: {license_id}", file=sys.stderr)
        link = f"https://pkg.go.dev/{path}@{version}" if version != "(main module)" else "—"
        license_file = found.name if found else "Not found in module cache"
        rows.append(f"| {path} | {version} | {license_id} | {license_file} | {link} |")

    content = """# Third-Party Notices

<!-- Generated by scripts/generate-third-party-notices.py; do not hand-edit the module table. -->

This inventory is generated from the resolved Go module graph using `go list -m -json all`. License identification is heuristic based on the first matching license file found in the Go module cache; any `UNKNOWN` or `review required` result requires human review before release. License text and notices must be preserved as required by each upstream license.

## Resolved Go module inventory

| Module | Resolved version | Detected license | License file | Upstream source |
|---|---:|---|---|---|
""" + "\n".join(rows) + """

## Regeneration and verification

Run from the repository root with the pinned Go toolchain:

```sh
go mod download
python3 scripts/generate-third-party-notices.py
git diff --exit-code -- THIRD-PARTY-NOTICES.md
```

The CI workflow regenerates the inventory and fails if it differs from the checked-in file. Dependency changes therefore require regeneration and license review. This inventory is not a substitute for legal review of upstream license terms.
"""
    OUTPUT.write_text(content, encoding="utf-8")
    print(f"Wrote {OUTPUT} for {len(modules)} modules")

if __name__ == "__main__":
    main()
