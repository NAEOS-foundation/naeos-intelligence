package main

import (
	"context"
	"errors"
	"fmt"
	"net/http"
	"os"
	"os/signal"
	"syscall"
	"time"

	"github.com/NAEOS-foundation/naeos-intelligence/internal/config"
	"github.com/NAEOS-foundation/naeos-intelligence/internal/httpapi"
)

const applicationName = "NAEOS Intelligence"

func run() error {
	cfg, err := config.Load(os.Environ())
	if err != nil {
		return err
	}

	addr := os.Getenv("NAEOS_INTELLIGENCE_HTTP_ADDR")
	if addr == "" {
		addr = "127.0.0.1:8080"
	}

	server := &http.Server{
		Addr:              addr,
		Handler:           httpapi.NewHandler(httpapi.NewMemoryStore(), httpapi.Authenticator{}),
		ReadHeaderTimeout: 5 * time.Second,
		ReadTimeout:       10 * time.Second,
		WriteTimeout:      15 * time.Second,
		IdleTimeout:       60 * time.Second,
	}

	ctx, stop := signal.NotifyContext(context.Background(), os.Interrupt, syscall.SIGTERM)
	defer stop()
	serverErr := make(chan error, 1)
	go func() {
		fmt.Printf("%s HTTP server starting (environment=%s log_level=%s addr=%s)\n",
			applicationName, cfg.App.Environment, cfg.App.LogLevel, addr)
		serverErr <- server.ListenAndServe()
	}()

	select {
	case err := <-serverErr:
		if errors.Is(err, http.ErrServerClosed) {
			return nil
		}
		return err
	case <-ctx.Done():
		shutdownCtx, cancel := context.WithTimeout(context.Background(), 10*time.Second)
		defer cancel()
		if err := server.Shutdown(shutdownCtx); err != nil {
			_ = server.Close()
			return fmt.Errorf("graceful HTTP shutdown: %w", err)
		}
		return nil
	}
}

func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}
